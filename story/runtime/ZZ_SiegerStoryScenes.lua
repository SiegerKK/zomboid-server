-- Checksum-identical code; private scene DATA is mounted outside auto-load Lua.
-- Accept ONLY storyctl.lua_literal's grammar. No loadstring, eval or remote code.
if isClient and isClient() then return end
local reader=getFileReader("SiegerStoryBundle.txt",false)
if not reader then error("Reviewed Story bundle data mount missing") end
local lines,size={},0
while true do
    local line=reader:readLine()
    if line==nil then break end
    size=size+#line+1
    if size>4*1024*1024 then reader:close();error("Story bundle too large") end
    lines[#lines+1]=line
end
reader:close()
local text=table.concat(lines,"\n")
local header="-- GENERATED by storyctl.py. Do not edit; source of truth is JSON.\nSiegerStoryScenes = "
if text:sub(1,#header)~=header then error("Unexpected Story data header") end
local pos=#header+1
local function skip() local _,last=text:find("^%s*",pos);pos=(last or pos-1)+1 end
local function stringValue()
    assert(text:sub(pos,pos)=='"',"Expected quoted data")
    pos=pos+1
    local out={}
    while pos<=#text do
        local ch=text:sub(pos,pos);pos=pos+1
        if ch=='"' then return table.concat(out) end
        if ch=='\\' then
            local digits=text:sub(pos,pos+2)
            assert(digits:match("^%d%d%d$") and tonumber(digits)<=255,"Invalid data escape")
            out[#out+1]=string.char(tonumber(digits));pos=pos+3
        else
            assert(ch:byte()>=32 and ch:byte()<127,"Unescaped non-ASCII data")
            out[#out+1]=ch
        end
    end
    error("Unterminated data string")
end
local value
value=function(depth)
    assert(depth<=20,"Story data nesting too deep")
    skip()
    local ch=text:sub(pos,pos)
    if ch=='"' then return stringValue() end
    if ch=='{' then
        pos=pos+1;skip()
        local result,index={},1
        while text:sub(pos,pos)~='}' do
            local key=text:match("^([A-Za-z_][A-Za-z0-9_]*)%s*=",pos)
            if key then
                pos=pos+#key;skip();assert(text:sub(pos,pos)=='=');pos=pos+1
                assert(result[key]==nil,"Duplicate Story key");result[key]=value(depth+1)
            else result[index]=value(depth+1);index=index+1 end
            skip();ch=text:sub(pos,pos)
            if ch==',' then pos=pos+1;skip() else assert(ch=='}',"Invalid Story data separator") end
        end
        pos=pos+1;return result
    end
    for _,literal in ipairs({"true","false","nil"}) do
        if text:sub(pos,pos+#literal-1)==literal then
            pos=pos+#literal
            if literal=="true" then return true elseif literal=="false" then return false else return nil end
        end
    end
    local number=text:match("^%-?%d+",pos)
    assert(number,"Non-data expression in Story bundle")
    pos=pos+#number;return tonumber(number)
end
local bundle=value(0);skip();assert(pos>#text,"Trailing non-data content")
assert(type(bundle)=="table" and bundle.schema==1 and type(bundle.world)=="string"
    and type(bundle.scenes)=="table" and type(bundle.inspect)=="table","Invalid Story data schema")
SiegerStoryScenes=bundle
print("SIEGER_STORY_BUNDLE_DATA loaded world="..bundle.world)
