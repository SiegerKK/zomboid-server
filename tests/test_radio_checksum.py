#!/usr/bin/env python3
"""B42 packaging: no injected vanilla Lua; private scene data is not executable."""
import os,sys,tempfile,subprocess,shutil,unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT/'scripts'),str(ROOT/'story')]
import radio_assets,storyctl,scanctl
from unittest.mock import patch
class ChecksumTests(unittest.TestCase):
 def test_pack_contains_all_public_server_modules(self):
  expected=radio_assets.render(radio_assets.load())
  for p,text in expected.items():self.assertEqual(p.read_text(),text,str(p))
  server=ROOT/'mods/SiegerRadio/42/media/lua/server'
  self.assertTrue((server/'SiegerRadioStation.lua').is_file())
  self.assertFalse((ROOT/'story/runtime/SiegerRadioStation.lua').exists())
  overlay=(ROOT/'compose.radio.yaml').read_text()
  self.assertNotIn('/pzomboid-server/media/lua/',overlay)
  self.assertIn('/root/Zomboid/Lua/SiegerStoryBundle.txt:ro',overlay)
  self.assertNotIn('SiegerRadioStation.lua:',(ROOT/'compose.story.yaml').read_text())
 def test_packaged_runtime_requires_exact_world_data_and_code_mounts(self):
  with patch.object(scanctl,'slot',side_effect=lambda world:Path('/tmp/isolated-worlds')/world):
   mounts={"/root/Zomboid/mods/SiegerRadio":(scanctl.REPO/"mods/SiegerRadio").resolve(),
           "/root/Zomboid/Lua/SiegerStoryBundle.txt":Path('/tmp/isolated-worlds/story_test/story/bundle.lua')}
   self.assertTrue(scanctl.packaged_runtime(mounts,"story_test"))
   self.assertFalse(scanctl.packaged_runtime(mounts,"other_world"))
   mounts["/root/Zomboid/mods/SiegerRadio"]=Path("/tmp/unreviewed")
   self.assertFalse(scanctl.packaged_runtime(mounts,"story_test"))
 def run_loader(self,bundle,client=False):
  lua=shutil.which('lua5.1')
  if not lua:self.skipTest('Lua5.1 required')
  with tempfile.TemporaryDirectory() as d:
   p=Path(d);(p/'bundle.txt').write_text(bundle)
   wrapper='''isClient=function()return CLIENT end
getFileReader=function(name,create)
 assert(name=="SiegerStoryBundle.txt" and create==false)
 local f=assert(io.open(arg[2],"rb"))
 return {readLine=function()return f:read("*l")end,close=function()f:close()end}
end
os.execute=function()error("EXECUTION FORBIDDEN")end
local ok,err=pcall(dofile,arg[1])
if not ok then io.stderr:write(tostring(err));os.exit(3)end
if not CLIENT then assert(SiegerStoryScenes.world=="story_test") end
'''.replace('CLIENT','true' if client else 'false')
   (p/'check.lua').write_text(wrapper)
   return subprocess.run([lua,str(p/'check.lua'),str(ROOT/'mods/SiegerRadio/42/media/lua/server/ZZ_SiegerStoryScenes.lua'),str(p/'bundle.txt')],capture_output=True,text=True)
 def test_loader_data_and_unicode(self):
  data={'schema':1,'world':'story_test','scenes':[{'pages':['Кириллица\n"\\', 'Page2'],'enabled':True,'count':-2}],'inspect':[]}
  text='-- GENERATED by storyctl.py. Do not edit; source of truth is JSON.\nSiegerStoryScenes = '+storyctl.lua_literal(data)+'\n'
  result=self.run_loader(text);self.assertEqual(result.returncode,0,result.stderr)
 def test_loader_rejects_executable_or_invalid_data(self):
  header='-- GENERATED by storyctl.py. Do not edit; source of truth is JSON.\nSiegerStoryScenes = '
  for value in ['os.execute("touch nope")','{schema=1};os.execute("nope")','{"unterminated}','{'*25+'}'*25]:
   result=self.run_loader(header+value);self.assertNotEqual(result.returncode,0);self.assertNotIn('EXECUTION FORBIDDEN',result.stderr)
 def test_client_never_reads_server_private_bundle(self):
  self.assertEqual(self.run_loader('INVALID SERVER DATA',True).returncode,0)
if __name__=='__main__':unittest.main(verbosity=2)
